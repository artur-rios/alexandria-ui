#!/usr/bin/env bash
# Runs every file of integration_test/ against the application on a desktop device, in as few launches as it can. Used by
# ci/integration.sh (Linux, under xvfb-run) and by the Windows leg of .github/workflows/ci.yml:
#
#     ci/integration-suite.sh <device> [command prefix...]
#
#     ci/integration-suite.sh linux xvfb-run -a
#     ci/integration-suite.sh windows
#
# On desktop, `flutter test` starts the application once per run, and the second file in a single invocation fails to
# launch with "Unable to start the app on the device", whichever file that happens to be. Every invocation also builds the
# application again for its own entry point, and copies the page engine into the bundle, before it can launch it. So the
# files are not run one invocation each: they are gathered into one generated entry point, each file's `main` in a group of
# its own (its setUpAll, setUp and tearDown stay scoped to its tests), and the application is built and started once.
#
# The page engine's test runs in an invocation of its own. Chromium is set up once per process and cannot be set up again,
# and whether that file expects the engine to start depends on the process (as root it expects a refusal), so it gets a
# process to itself, as it does in the sandboxed GitHub Actions job.
#
# The generated file is never committed (.gitignore) and is rebuilt from the directory on every run, so a new test file is
# picked up without anyone having to list it.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

device=${1:?usage: ci/integration-suite.sh <device> [command prefix...]}
shift

isolated=integration_test/viewers/saved_page_engine_test.dart
entry=integration_test/all_suites.g.dart

mapfile -t suites < <(find integration_test -name '*_test.dart' ! -path "$isolated" | sort)
if [ "${#suites[@]}" -eq 0 ]; then
  echo "ci/integration-suite.sh: no integration test files found" >&2
  exit 1
fi

{
  echo '// Generated by ci/integration-suite.sh. Do not edit and do not commit.'
  echo "import 'package:flutter_test/flutter_test.dart';"
  echo "import 'package:integration_test/integration_test.dart';"
  echo
  index=0
  for suite in "${suites[@]}"; do
    echo "import '${suite#integration_test/}' as suite$index;"
    index=$((index + 1))
  done
  echo
  echo 'void main() {'
  echo '  IntegrationTestWidgetsFlutterBinding.ensureInitialized();'
  echo
  index=0
  for suite in "${suites[@]}"; do
    echo "  group('${suite#integration_test/}', suite$index.main);"
    index=$((index + 1))
  done
  echo '}'
} > "$entry"

echo "== Integration suite: ${#suites[@]} files in one launch"
printf '   %s\n' "${suites[@]}"
"$@" flutter test "$entry" -d "$device"

if [ -f "$isolated" ]; then
  echo "== $isolated"
  "$@" flutter test "$isolated" -d "$device"
fi
